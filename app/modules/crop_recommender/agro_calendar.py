def get_current_indian_season(month: int) -> str:
    if 6 <= month <= 10:
        return 'खरीफ (Kharif - मानसून)'
    elif month >= 11 or month <= 2:
        return 'रबी (Rabi - शीतकालीन)'
    else:
        return 'जायद (Zaid - ग्रीष्मकालीन)'
